-- ============================================================================
-- 0040 — تغيير الزيت: مبلغ وتاريخ، يُخصم من الربح
-- ============================================================================
--
-- 🔒 إضافي: عمود واحد وفهرس. لا delete ولا truncate ولا drop table ولا جدول
--    جديد، و**لا تُمَس أي دالة ربح**.
--
-- المطلوب: خانة أكتب فيها مبلغ تغيير الزيت وتاريخه، والمجموع يُخصم من الربح.
--
-- ----------------------------------------------------------------------------
-- لماذا لا جدول جديد
--
-- جدول expenses موجود ويُخصم من الربح **بالفعل** في الموضعين معاً:
--   fn_financial_summary   →  exp_agg ... from expenses where date between ...
--   fn_dashboard_overview  →  exp     ... from expenses
--
-- فتغيير الزيت مصروف شركة عادي، ومكانه الطبيعي هذا الجدول. الناقص وحده هو
-- ربطه بالسائق حتى يظهر في صفحته. عمود واحد يكفي.
--
-- والمكسب: **صفر تعديل على معادلة الربح**، فلا خطر انحراف — وتعديل دالتَي
-- الربح معاً قاعدة مكتوبة في PROJECT_CONTEXT بعد أن وقع إغفال إحداهما ثلاث مرات.
--
-- ----------------------------------------------------------------------------
-- ملاحظة على المسارات الأخرى
--
-- الزيت المدفوع **من عهدة السائق أو من جيبه** يُسجَّل كما هو اليوم: قيد عهدة
-- ببند «صيانة». فمن جيبه يدخل كشفه ضمن «ما صرفه على العمل» ويُضاف لمستحقاته.
-- هذا يعمل منذ 0012 ولا يحتاج شيئاً.
--
-- وهذا العمود **لمصروف الشركة المباشر** — لا يُضاف لمستحقات السائق ولا يُطالَب
-- به، بخلاف ما يدفعه من ماله.
--
-- الملف قابل لإعادة التشغيل بأمان.
-- ----------------------------------------------------------------------------

alter table expenses
  add column if not exists driver_id uuid references drivers(id) on delete set null;

create index if not exists idx_expenses_driver
  on expenses(driver_id, date desc) where driver_id is not null;
