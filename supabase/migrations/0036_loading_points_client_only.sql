-- ============================================================================
-- 0036 — مواقع التحميل: على العميل لا على السائق
-- ============================================================================
--
-- 🔒 إضافي: إعادة تعريف دالة واحدة. لا delete ولا truncate ولا drop table،
--    و**لا إعادة حساب لأي رحلة مسجَّلة** — خلافاً لـ 0026 الذي أعاد الحساب.
--
-- القاعدة الصحيحة: السائق يُحاسَب على **التنزيل** فقط. مدن التحميل لا تُحسب له
-- ترب موقع إضافي:
--
--     التحميل من: الكتشن الجديد + القديم   ← موقعا تحميل
--     السائق: لا شيء إضافي                  ← يُحاسَب على التنزيل وحده
--     العميل: يُحاسَب على الموقع الزائد      ← كما هو اليوم، بلا تغيير
--
-- التغيير: fn_driver_extra_stops كانت تجمع الاثنين
--
--     fn_chargeable_stops(الفروع، إلى)  +  fn_extra_loading_points(من)
--
-- وصارت الأولى وحدها.
--
-- ⚠️ هذا يعكس ما استعاده 0026. وقتها أُضيفت نقاط التحميل لترب السائق لأن 0025
--    أسقطها بغير قصد حين توقّف trip_locations عن تغذية الحساب، فاستُعيدت حفاظاً
--    على السلوك السابق — لا لأن قاعدة عمل نصّت عليها. الآن القاعدة منصوصة.
--
-- 🔒 جانب العميل لم يُلمس: fn_extra_loading_points باقية كما هي، وأجرة التحميل
--    الإضافي للعميل (extra_loading_fare) تُحسب منها في الواجهة وفي 0019 بلا
--    أي تغيير. المتغيّر هو نصيب السائق فقط.
--
-- 📌 الرحلات المسجَّلة تحتفظ بأرقامها: المشغّل يعمل عند الكتابة فقط، ولم أُعِد
--    حساب أي صف. لكن **رحلة قديمة تُعدَّل بعد اليوم سيُعاد حساب تربها بالقاعدة
--    الجديدة**، فينقص بمقدار نقاط التحميل. هذا مقصود — القاعدة الجديدة هي
--    الصحيحة — لكن أحببت أن يكون مكتوباً لا مكتشَفاً.
--
-- الاسم p_from_location يبقى في التوقيع وإن لم يُستخدم: تغييره يستلزم تعديل
-- المشغّل وكل نداء، بلا مقابل.
--
-- الملف قابل لإعادة التشغيل بأمان.
-- ----------------------------------------------------------------------------

create or replace function fn_driver_extra_stops(
  p_branches_count int,
  p_from_location  text,
  p_to_location    text
)
returns int
language sql
immutable
as $fn$
  -- التنزيل وحده. مدن التحميل تُحاسَب على العميل لا على السائق.
  select fn_chargeable_stops(p_branches_count, p_to_location);
$fn$;
