-- 0037 — مزامنة جوجل شيت: علامة المصدر ورابط الشيت
-- ============================================================================
--
-- 🔒 إضافي بالكامل: عمودان جديدان وفهرس. لا delete ولا truncate ولا drop table.
--    الرحلات المسجَّلة لا تُمس، والمزامنة تُدخل الجديد فقط ولا تحذف شيئاً.
--
-- المشكلة التي يحلّها source_key: لو جرت المزامنة مرتين، ما الذي يمنع إنشاء كل
-- رحلة مرتين؟ لا مفتاح طبيعي في الشيت. فنحفظ على كل رحلة مستوردة علامة مصدرها:
--
--     gsheet:<معرّف الشيت>:<gid>:<الرقم التسلسلي في العمود #>
--
-- والفهرس الفريد يمنع تكرارها حتى لو أُرسل نفس الصف مرتين — حماية في قاعدة
-- البيانات لا في الواجهة وحدها.
--
-- ⚠️ الرقم التسلسلي مفتاحنا لأن الشركة تضيف على نفس التبويب بترقيم متسلسل
--    مُعدّ مسبقاً. لو أُعيد ترتيب الصفوف أو حُذف صف وأُعيد ترقيم ما بعده، قد
--    يُقرأ صف قديم كأنه جديد — ولهذا **المزامنة تعرض معاينة قبل الاعتماد**
--    ولا تكتب شيئاً وحدها.
--
-- الملف قابل لإعادة التشغيل بأمان.
-- ----------------------------------------------------------------------------

-- علامة المصدر — فارغة للرحلات المُدخلة يدوياً أو المستوردة من Excel
alter table trips
  add column if not exists source_key text;

create unique index if not exists idx_trips_source_key
  on trips(source_key) where source_key is not null;

-- رابط الشيت في الإعدادات لا في الكود: الشركة قد ترسل رابطاً جديداً، فيُغيَّر
-- من الواجهة بلا نشر جديد.
alter table settings
  add column if not exists trips_sheet_url text;
