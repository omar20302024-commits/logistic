/**
 * تطبيع النص العربي قبل المقارنة.
 *
 * السبب: مطابقة أسماء المدن (خطوط سير السائق) كانت تعتمد على `trim().toLowerCase()`
 * فقط، و`toLowerCase()` لا يؤثر على الحروف العربية إطلاقاً — فكانت المطابقة حرفية
 * بالكامل. أي اختلاف إملائي شائع (جده/جدة، الاحساء/الأحساء، مسافة زائدة) كان يفشل
 * المطابقة ويرجع للترب الافتراضي العام بدل ترب خط السير المحدَّد.
 *
 * ملاحظة مهمة: هذه الدالة للمقارنة فقط — لا تُحفظ نتيجتها في قاعدة البيانات ولا
 * تُعرض للمستخدم. النص الأصلي كما كتبه المستخدم يبقى كما هو دائماً.
 *
 * ما لا تفعله عمداً: لا تحذف أداة التعريف "ال" — لأن "العلا" و"علا" مدينتان
 * مختلفتان، وحذفها كان سيُنتج مطابقات خاطئة.
 *
 * WARNING to anyone editing the character ranges below:
 * النطاقات مكتوبة بحروف عربية مباشرة داخل [ ]، وترتيب عرضها في المحرر (BiDi) لا
 * يطابق ترتيب تخزينها. وده مش كلام نظري — حصل فعلاً أثناء كتابة الملف ده: نطاق
 * التشكيل اتخزّن كـ U+064B ثم "-" ثم U+0670 ثم U+065F، يعني المدى U+064B..U+0670،
 * وهو بيبتلع في طريقه U+0660..U+0669 (الأرقام العربية-الهندية) فيحذفها بدل ما
 * تتحوّل. الخطأ ده مستحيل تشوفه بالعين لأن السطر بيبان مظبوط على الشاشة.
 *
 * الترتيب المخزَّن الصحيح المطلوب (لاحظ أن U+0670 مفردة، مش طرف مدى):
 *   DIACRITICS             -> U+064B  -  U+065F  U+0670
 *   ARABIC_INDIC_DIGITS    -> U+0660  -  U+0669
 *   EXTENDED_ARABIC_DIGITS -> U+06F0  -  U+06F9
 *
 * بعد أي تعديل على النطاقات، تحقّق من الترتيب المخزَّن فعلاً لا من شكله في المحرر.
 * أسرع فحص سلوكي: normalizeArabic("٢٠٢٤") لازم ترجع "2024" — لو رجعت "" فالنطاق
 * بيبتلع الأرقام.
 */

// التشكيل: التنوين والحركات والشدة والسكون (U+064B..U+065F) + الألف الخنجرية (U+0670)
const DIACRITICS = /[ً-ٰٟ]/g;

// التطويل (الكشيدة) — حرف زخرفي بلا قيمة صوتية
const TATWEEL = /ـ/g;

// الأرقام العربية-الهندية ٠-٩
const ARABIC_INDIC_DIGITS = /[٠-٩]/g;

// الأرقام الفارسية ۰-۹
const EXTENDED_ARABIC_DIGITS = /[۰-۹]/g;

/**
 * الحروف التي تُكتب بأكثر من صورة للمعنى نفسه.
 *
 * الأخيران ليسا خطأً إملائياً بل حرفان فارسيان (U+06CC، U+06A9) يتسللان كثيراً إلى
 * النص العربي عند النسخ من الويب أو من لوحات مفاتيح مختلطة، ويبدوان للعين مطابقين
 * تماماً للعربي بينما هما نقطتا ترميز مختلفتان — وهما من أخبث أسباب فشل المطابقة.
 */
const LETTER_MAP: Record<string, string> = {
  "آ": "ا", // آ → ا
  "أ": "ا", // أ → ا
  "إ": "ا", // إ → ا
  "ٱ": "ا", // ٱ → ا
  "ى": "ي", // ى → ي (ألف مقصورة)
  "ة": "ه", // ة → ه (تاء مربوطة)
  "ؤ": "و", // ؤ → و
  "ئ": "ي", // ئ → ي
  "ی": "ي", // ی → ي (ياء فارسية)
  "ک": "ك", // ک → ك (كاف فارسية)
};

// يُشتق صنف الحروف من مفاتيح الخريطة نفسها — حتى يستحيل أن ينزلق أحدهما عن الآخر
// عند إضافة حرف جديد لاحقاً
const LETTER_VARIANTS = new RegExp(`[${Object.keys(LETTER_MAP).join("")}]`, "g");

export function normalizeArabic(input: string): string {
  return input
    .replace(DIACRITICS, "")
    .replace(TATWEEL, "")
    .replace(ARABIC_INDIC_DIGITS, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(EXTENDED_ARABIC_DIGITS, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(LETTER_VARIANTS, (c) => LETTER_MAP[c] ?? c)
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
